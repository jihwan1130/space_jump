/**
 * 레슨을 평탄화한 **행성 코스**.
 *
 * game.js는 예전과 똑같이 이 배열의 인덱스로 행성을 하나씩 세워요.
 * 레슨은 "카드를 몇 장 띄우고 진행을 어떻게 세느냐"만 바꾼 거라,
 * 코스를 만드는 쪽 코드는 건드릴 필요가 없어요.
 *
 * card는 **레슨의 첫 칸에만** 붙어요. 그게 모달이 7장으로 줄어드는 이유예요.
 */
export const TUTORIAL_COURSE = TUTORIAL_LESSONS.flatMap((lesson, li) =>
  lesson.steps.map((step, si) => ({
    ...step,
    lesson: li,
    lessonName: lesson.name,
    card: si === 0 ? lesson.card : null,
  }))
);

